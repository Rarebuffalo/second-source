"""``second-source init``: write the recommended workflow into a repository.

Setup should be one command and one commit. The generated workflow re-checks PRs when CI
finishes (``workflow_run``), which needs the names of the repository's CI workflows; they are
read from ``.github/workflows`` so nobody has to type them.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

WORKFLOW_DIR = Path(".github/workflows")
WORKFLOW_FILE = WORKFLOW_DIR / "second-source.yml"
CI_TRIGGERS = frozenset({"push", "pull_request", "pull_request_target"})
# One run at a time per PR, so two events cannot publish out of order.
_CONCURRENCY_KEY = (
    "${{ github.event.pull_request.number || github.event.issue.number || github.run_id }}"
)


def _triggers(document: dict[Any, Any]) -> set[str]:
    # YAML 1.1 reads a bare `on:` key as the boolean True, so look under both.
    on = document.get("on", document.get(True))
    if isinstance(on, str):
        return {on}
    if isinstance(on, list):
        return {str(item) for item in on}
    if isinstance(on, dict):
        return {str(key) for key in on}
    return set()


def ci_workflow_names(root: Path) -> list[str]:
    """Names of the workflows that run on pushes or PRs (the repository's CI), sorted.

    A workflow without a ``name`` is known to GitHub by its file path, so that is used.
    """
    names = []
    directory = root / WORKFLOW_DIR
    for path in sorted([*directory.glob("*.yml"), *directory.glob("*.yaml")]):
        if path.name == WORKFLOW_FILE.name:
            continue
        try:
            document = yaml.safe_load(path.read_text(encoding="utf-8"))
        except (OSError, yaml.YAMLError):
            continue  # an unreadable workflow is skipped, not fatal
        if isinstance(document, dict) and _triggers(document) & CI_TRIGGERS:
            names.append(str(document.get("name") or path.relative_to(root).as_posix()))
    return sorted(set(names))


def workflow_text(ci_names: list[str], action_ref: str = "Rarebuffalo/second-source@v1") -> str:
    if ci_names:
        quoted = ", ".join(f'"{name}"' for name in ci_names)
        workflow_run = (
            "  # Re-check when CI finishes, so verdicts no longer wait on it.\n"
            "  workflow_run:\n"
            f"    workflows: [{quoted}]\n"
            "    types: [completed]\n"
        )
    else:
        workflow_run = (
            "  # No CI workflows were found. Add `workflow_run` with your CI workflow names to\n"
            "  # re-check as soon as CI finishes; until then the daily run catches up.\n"
        )
    return f"""\
# Second Source: checks the claims coding agents make in their pull requests.
# Generated by `second-source init`. Docs: https://github.com/Rarebuffalo/second-source
#
# Safe with pull_request_target: Second Source reads the PR through the API only and never
# checks out or runs its code. Do not add an actions/checkout step to this workflow.
name: Second Source

on:
  pull_request_target:
    types: [opened, edited, synchronize, reopened, ready_for_review, closed]
{workflow_run}  issue_comment:
    types: [created]
  schedule:
    - cron: "17 6 * * *"  # daily: durability (reverts, reopened issues) and pending claims
  workflow_dispatch:

permissions:
  checks: write
  contents: read
  pull-requests: read
  issues: write
  actions: read

concurrency:
  group: second-source-{_CONCURRENCY_KEY}
  cancel-in-progress: false

jobs:
  check:
    # Comments only matter when they hold a /second-source command on a pull request.
    if: >-
      github.event_name != 'issue_comment' ||
      (github.event.issue.pull_request && contains(github.event.comment.body, '/second-source'))
    runs-on: ubuntu-latest
    steps:
      - uses: {action_ref}
"""


class WorkflowExists(FileExistsError):
    """The workflow file is already there and overwriting was not asked for."""


def write_workflow(root: Path, *, force: bool = False) -> tuple[Path, list[str]]:
    """Write the workflow; return its path and the CI workflow names it follows."""
    path = root / WORKFLOW_FILE
    if path.exists() and not force:
        raise WorkflowExists(str(path))
    names = ci_workflow_names(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(workflow_text(names), encoding="utf-8")
    return path, names
